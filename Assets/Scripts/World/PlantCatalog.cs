using System;
using System.Collections.Generic;
using System.Linq;
using NaturalHistory.Core;
using UnityEngine;

namespace NaturalHistory.World
{
    // One plant species shown on the map (plants.json). Purely visual: plants have no game effect.
    [Serializable]
    public class PlantDefinition
    {
        public string id;
        public string commonName;
        public string scientificName;
        public string group;          // e.g. "Lycopsid", "Seed fern", "Conifer", "Flowering plant"
        public string firstAge;       // GeologicalAge names; empty lastAge = still alive
        public string lastAge;
        public string layer;          // "canopy" (forest trees) or "ground" (open ground, understory)
        public List<string> terrains; // TerrainKind names as the map shows them in the plant's period
        public List<string> forests;  // canopy: forest types it forms (Broadleaf, Conifer, Jungle)
        public string form;           // mesh shape, see MapFeatureMeshes.AddCanopyPlant / AddGroundPlant
        public string shape;          // silhouette within the form (Broadleaf: Round, Dome, Oval, Tall, Slender, ...; see PlantShapes.cs); empty = the form's default
        public float rarity;          // 0 = common .. 1 = rare: lowers its chance to be a region's plant (colourful trees)
        public string crown;          // hex: the whole crown in this colour (cherry pink, Japanese-maple red, jacaranda purple); empty = green leaves
        public string blossom;        // hex colour of its flowers on the map; empty = none shown
        public string fruit;          // hex colour of its fruit, cones or spore cones; empty = none shown
        public string fruitForm;      // Round, Berry, Nut, Samara, Ball, Catkin, Cone, UprightCone, Pod, Hanging, Coconut, Strobilus, Seed (see PlantShapes.cs)
        public string tint;           // hex; multiplies the form's leaf colours (white = as is)
        public float size = 1f;
        public string description;

        [NonSerialized] public Color Tint = Color.white;
        [NonSerialized] public GeologicalAge First, Last;

        public bool IsCanopy => layer == "canopy";
        public bool AliveIn(GeologicalAge age) => age >= First && age <= Last;

        // "Scale tree (Lepidodendron aculeatum)"; just the name when they're the same
        public string Label => string.IsNullOrEmpty(scientificName) || scientificName.StartsWith(commonName, StringComparison.OrdinalIgnoreCase)
            ? (string.IsNullOrEmpty(scientificName) ? Loc.T(commonName) : scientificName)
            : $"{Loc.T(commonName)} ({scientificName})";
    }

    [Serializable]
    public class PlantCollection
    {
        public List<PlantDefinition> plants;
    }

    // Loads Resources/Data/plants.json (generated by tools/flora/plants.py) on first use.
    public static class PlantCatalog
    {
        private static List<PlantDefinition> plants;

        public static IReadOnlyList<PlantDefinition> All { get { Load(); return plants; } }

        public static List<PlantDefinition> AliveIn(GeologicalAge age) => All.Where(p => p.AliveIn(age)).ToList();

        private static void Load()
        {
            if (plants != null) return;
            plants = new List<PlantDefinition>();
            var asset = Resources.Load<TextAsset>("Data/plants");
            if (asset == null) { Debug.LogError("[PlantCatalog] Missing Resources/Data/plants.json"); return; }
            var data = JsonUtility.FromJson<PlantCollection>(asset.text);
            foreach (var p in data?.plants ?? new List<PlantDefinition>())
            {
                if (string.IsNullOrEmpty(p.id)) continue;
                p.terrains ??= new List<string>();
                p.forests  ??= new List<string>();
                if (p.size <= 0f) p.size = 1f;
                if (!ColorUtility.TryParseHtmlString(p.tint, out p.Tint)) p.Tint = Color.white;
                p.First = Enum.TryParse(p.firstAge, true, out GeologicalAge f) ? f : GeologicalAge.Ediacaran;
                p.Last  = Enum.TryParse(p.lastAge,  true, out GeologicalAge l) ? l : GeologicalAge.Quaternary;
                plants.Add(p);
            }
            Debug.Log($"[PlantCatalog] {plants.Count} plant species");
        }
    }
}
